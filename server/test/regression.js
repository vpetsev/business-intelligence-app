const assert = require('assert').strict;
process.env.JWT_PASSWORD = 'integration-test-secret';
const { prepare, start, models } = require('./support');
const jwt = require('jsonwebtoken');
let server;
(async () => {
  await prepare();
  assert(!models.SavedData.rawAttributes.UserId, 'Do not create a second association column');
  await models.Company.findAll(); // All model columns must exist after migrations.
  server = await start(require('../app'));
  const call = server.request;
  const first = { username: 'owner@example.test', password: 'test-password' };
  const second = { username: 'other@example.test', password: 'another-password' };
  for (const body of [first, second]) assert.equal((await call('/register', { method: 'POST', body })).status, 201);
  assert.equal((await call('/register', { method: 'POST', body: first })).status, 409);
  assert.equal((await call('/api/login', { method: 'POST', body: { username: 'missing', password: 'wrong' } })).status, 401);
  assert.equal((await call('/api/login', { method: 'POST', body: { ...first, password: 'wrong' } })).status, 401);
  assert.equal((await call('/api/login', { method: 'POST', body: {} })).status, 400);
  const login = await call('/api/login', { method: 'POST', body: first });
  assert.equal(login.status, 200);
  const { token, userId } = login.json;
  assert.equal(jwt.verify(token, process.env.JWT_PASSWORD).id, userId);
  const other = (await call('/api/login', { method: 'POST', body: second })).json;
  const route = '/userData/user-data/' + userId;
  assert.equal((await call(route)).status, 401);
  assert.equal((await call(route, { token: 'invalid' })).status, 401);
  assert.equal((await call(route, { token: jwt.sign({ id: userId }, 'wrong-secret') })).status, 401);
  assert.equal((await call(route, { token: jwt.sign({ id: userId }, process.env.JWT_PASSWORD, { expiresIn: -1 }) })).status, 401);
  assert.equal((await call(route, { token: other.token })).status, 403);
  assert.equal((await call('/api/data', { method: 'POST', body: [] })).status, 401);
  assert.equal((await call('/api/data', { method: 'POST', token, body: [] })).status, 400);
  const uploaded = await call('/api/data', { method: 'POST', token, body: [{ Revenue: '123', Expenses: '12', company: 'Owner data', userId: other.userId }] });
  assert.equal(uploaded.status, 201);
  assert.equal(uploaded.json.count, 1);
  const ownRows = await call(route, { token });
  assert.equal(ownRows.status, 200);
  assert.equal(ownRows.json.length, 1);
  assert.equal(ownRows.json[0].userId, userId);
  assert.equal((await call('/userData/user-data/' + other.userId, { token: other.token })).json.length, 0);
  process.env.REACT_APP_USERNAME = first.username;
  process.env.REACT_APP_PASSWORD = first.password;
  const guest = await call('/api/guest-login', { method: 'POST', body: {} });
  assert.equal(guest.status, 200);
  assert.equal(jwt.verify(guest.json.token, process.env.JWT_PASSWORD).id, userId);
  delete process.env.REACT_APP_USERNAME;
  assert.equal((await call('/api/guest-login', { method: 'POST', body: {} })).status, 503);
  await models.sequelize.query('ALTER TABLE "SavedData" RENAME TO "SavedDataUnavailable"');
  assert.equal((await call('/api/data', { method: 'POST', token, body: [{ company: 'Database failure' }] })).status, 500);
  await models.sequelize.query('ALTER TABLE "SavedDataUnavailable" RENAME TO "SavedData"');
  console.log('PASS: fresh migrations, login failures, token verification, guest identity, data isolation, upload ownership/completion and database-error responses');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  if (server) await server.close();
  await models.sequelize.close();
});

